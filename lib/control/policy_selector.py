"""Bounded, auditable selection among legal behavior configurations.

This selector is deliberately small. It considers only candidates generated by
the deterministic controller and scores them from explicit evidence fields.
Validated experiment receipts may change the ordering; raw behavioral history
cannot.
"""
from __future__ import annotations

from dataclasses import dataclass, field
import hashlib
import json
from types import MappingProxyType
from typing import Any, Iterable, Mapping, Sequence

from ..behavior_state import (BEHAVIOR_MODES, FRAMEWORK_MODES, BehaviorState,
                              AttentionLease, CSWBehaviorSnapshot, GoalSetSnapshot)
from ..attention import projected_starvation_risk
from ..routing_profiles import RoutingProfileError, condition_matches, validate_profile


POLICY_PRIOR_VERSION = "1.0.0"
_CONTROL_VALUES = {
    "verification_intensity": {"passive", "normal", "high", "strict"},
    "exploration_budget": {"disabled", "low", "normal", "bounded"},
    "retry_policy": {"normal", "materially_different_only", "no_retry"},
    "recovery_level": {0, 1, 2, 3},
    "context_strategy": {"standard", "compact", "criterion_focused"},
    "response_strategy": {"direct", "detailed", "structured"},
}
_CONTROL_NAMES = tuple(_CONTROL_VALUES)
_MAX_CANDIDATES = 8
_MAX_PRIORS = 64
_VALIDATED_PRIOR_SEAL = object()


@dataclass(frozen=True)
class CandidateEvidence:
    """Evidence about a policy, keeping missing measurements explicitly unknown."""

    correct_progress_estimate: float | None = None
    regression_estimate: float | None = None
    repeated_failure_estimate: float | None = None
    sample_count: int = 0
    holdout_count: int = 0
    evidence_class: str = "unknown"
    confidence_interval: tuple[float, float] | None = None
    regression_confidence_interval: tuple[float, float] | None = None
    repeated_failure_confidence_interval: tuple[float, float] | None = None

    def __post_init__(self) -> None:
        if self.evidence_class not in {
                "deterministic_rule", "validated_experiment", "semantic_support", "unknown"}:
            raise ValueError("unsupported candidate evidence class")
        for name in ("correct_progress_estimate", "regression_estimate",
                     "repeated_failure_estimate"):
            value = getattr(self, name)
            if value is not None and (type(value) not in (int, float)
                                      or not 0.0 <= float(value) <= 1.0):
                raise ValueError(f"{name} must be a probability estimate or unknown")
        for name in ("confidence_interval", "regression_confidence_interval",
                     "repeated_failure_confidence_interval"):
            value = getattr(self, name)
            if value is not None:
                interval = tuple(value)
                if (len(interval) != 2
                        or any(type(item) not in (int, float)
                               or not 0.0 <= float(item) <= 1.0 for item in interval)
                        or interval[0] > interval[1]):
                    raise ValueError(f"{name} must be an ordered probability interval")
                object.__setattr__(self, name, (float(interval[0]), float(interval[1])))
        if (type(self.sample_count) is not int or self.sample_count < 0
                or type(self.holdout_count) is not int or self.holdout_count < 0):
            raise ValueError("candidate evidence counts must be non-negative integers")
        if self.evidence_class == "validated_experiment":
            if (self.correct_progress_estimate is None or self.regression_estimate is None
                    or self.repeated_failure_estimate is None or self.sample_count < 1
                    or self.holdout_count < 1 or self.confidence_interval is None
                    or self.regression_confidence_interval is None
                    or self.repeated_failure_confidence_interval is None):
                raise ValueError("validated experiment evidence must carry explicit rates and intervals")
        elif any(value is not None for value in (
                self.correct_progress_estimate, self.regression_estimate,
                self.repeated_failure_estimate)):
            raise ValueError("non-experimental evidence cannot claim empirical rates")

    def to_dict(self) -> dict[str, Any]:
        return {
            "correct_progress_estimate": self.correct_progress_estimate,
            "regression_estimate": self.regression_estimate,
            "repeated_failure_estimate": self.repeated_failure_estimate,
            "sample_count": self.sample_count,
            "holdout_count": self.holdout_count,
            "evidence_class": self.evidence_class,
            "confidence_interval": (list(self.confidence_interval)
                                    if self.confidence_interval is not None else None),
            "regression_confidence_interval": (
                list(self.regression_confidence_interval)
                if self.regression_confidence_interval is not None else None),
            "repeated_failure_confidence_interval": (
                list(self.repeated_failure_confidence_interval)
                if self.repeated_failure_confidence_interval is not None else None),
        }


def _canonical(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False, allow_nan=False)


def candidate_id_for(*, cognitive_mode: str, framework_modes: Mapping[str, str],
                     controls: Mapping[str, Any], focus_scope: str,
                     statework_preferences: Iterable[str],
                     focus_criteria: Iterable[str] = ()) -> str:
    """Return a stable identity for an exact or attention-bound policy."""
    if focus_scope not in {"current_attention", "explicit"}:
        raise ValueError("unsupported policy focus scope")
    identity = {
        "candidate_version": "1.0.0",
        "cognitive_mode": cognitive_mode,
        "framework_modes": dict(sorted((str(k).lower(), str(v))
                                        for k, v in framework_modes.items())),
        "controls": dict(sorted(controls.items())),
        "focus_scope": focus_scope,
        "focus_criteria": (list(focus_criteria) if focus_scope == "explicit" else []),
        "statework_preferences": list(statework_preferences),
    }
    return "behavior-" + hashlib.sha256(_canonical(identity).encode()).hexdigest()[:24]


@dataclass(frozen=True)
class BehaviorCandidate:
    """One bounded behavior configuration considered by the fast loop."""

    candidate_id: str
    cognitive_mode: str
    framework_modes: Mapping[str, str]
    controls: Mapping[str, Any]
    focus_criteria: tuple[str, ...]
    statework_preferences: tuple[str, ...]
    reason_codes: tuple[str, ...] = ()
    focus_scope: str = "current_attention"
    cause: str = "deterministic_policy"
    expected_effect: str = "Apply the selected bounded behavior policy."

    def __post_init__(self) -> None:
        if not isinstance(self.candidate_id, str) or not self.candidate_id or len(self.candidate_id) > 128:
            raise ValueError("behavior candidate ID must be bounded text")
        if self.cognitive_mode not in BEHAVIOR_MODES:
            raise ValueError("behavior candidate has an unsupported cognitive mode")
        frameworks = {str(key).lower(): str(value)
                      for key, value in self.framework_modes.items()}
        if (len(frameworks) > 16 or any(value not in FRAMEWORK_MODES
                                        for value in frameworks.values())):
            raise ValueError("behavior candidate framework modes are malformed")
        controls = dict(self.controls)
        if set(controls) != set(_CONTROL_NAMES):
            raise ValueError("behavior candidate must specify every bounded control")
        if any(value not in _CONTROL_VALUES[key] for key, value in controls.items()):
            raise ValueError("behavior candidate controls are malformed")
        focus = tuple(self.focus_criteria)
        preferences = tuple(self.statework_preferences)
        reasons = tuple(self.reason_codes)
        for name, values, maximum in (("focus criteria", focus, 8),
                                      ("StateWork preferences", preferences, 4),
                                      ("reason codes", reasons, 16)):
            if (len(values) > maximum or len(values) != len(set(values))
                    or any(not isinstance(value, str) or not value or len(value) > 128
                           for value in values)):
                raise ValueError(f"behavior candidate {name} exceed their bounds")
        if self.focus_scope not in {"current_attention", "explicit"}:
            raise ValueError("unsupported behavior candidate focus scope")
        if not isinstance(self.cause, str) or not self.cause or len(self.cause) > 128:
            raise ValueError("behavior candidate cause must be bounded text")
        if (not isinstance(self.expected_effect, str) or not self.expected_effect.strip()
                or len(self.expected_effect) > 512):
            raise ValueError("behavior candidate expected effect must be bounded text")
        expected_id = candidate_id_for(
            cognitive_mode=self.cognitive_mode, framework_modes=frameworks,
            controls=controls, focus_scope=self.focus_scope,
            statework_preferences=preferences, focus_criteria=focus)
        if self.candidate_id != expected_id:
            raise ValueError("behavior candidate ID does not match its configuration")
        object.__setattr__(self, "framework_modes", MappingProxyType(frameworks))
        object.__setattr__(self, "controls", MappingProxyType(controls))
        object.__setattr__(self, "focus_criteria", focus)
        object.__setattr__(self, "statework_preferences", preferences)
        object.__setattr__(self, "reason_codes", reasons)

    @classmethod
    def from_state(cls, state: BehaviorState, *, focus_criteria: Iterable[str],
                   statework_preferences: Iterable[str], reason_codes: Iterable[str],
                   cause: str, expected_effect: str,
                   focus_scope: str = "current_attention") -> "BehaviorCandidate":
        controls = {name: getattr(state, name) for name in _CONTROL_NAMES}
        frameworks = dict(state.framework_modes)
        frameworks["ward"] = "mandatory"
        focus = tuple(focus_criteria)
        preferences = tuple(statework_preferences)
        return cls(
            candidate_id=candidate_id_for(
                cognitive_mode=state.cognitive_mode, framework_modes=frameworks,
                controls=controls, focus_scope=focus_scope,
                statework_preferences=preferences,
                focus_criteria=focus),
            cognitive_mode=state.cognitive_mode,
            framework_modes=frameworks, controls=controls,
            focus_criteria=focus,
            statework_preferences=preferences,
            reason_codes=tuple(reason_codes), focus_scope=focus_scope,
            cause=cause, expected_effect=expected_effect)

    @classmethod
    def from_policy_mapping(cls, value: Mapping[str, Any], *,
                            attention_criteria: Iterable[str]) -> "BehaviorCandidate":
        data = dict(value)
        allowed = {"candidate_id", "cognitive_mode", "framework_modes", "controls",
                   "focus_scope", "focus_criteria", "statework_preferences",
                   "reason_codes", "cause", "expected_effect"}
        if set(data) - allowed:
            raise ValueError("behavior policy candidate contains unknown fields")
        focus_scope = str(data.get("focus_scope") or "current_attention")
        if focus_scope != "current_attention":
            raise ValueError("promoted policies must bind focus to current host attention")
        if data.get("focus_criteria", "$current_attention") != "$current_attention":
            raise ValueError("promoted policies cannot override the host attention lease")
        focus = tuple(attention_criteria)
        candidate = cls(
            candidate_id=str(data.get("candidate_id") or ""),
            cognitive_mode=str(data["cognitive_mode"]),
            framework_modes=dict(data.get("framework_modes") or {}),
            controls=dict(data["controls"]),
            focus_criteria=focus,
            statework_preferences=tuple(data.get("statework_preferences") or ()),
            reason_codes=tuple(data.get("reason_codes") or ("validated_policy_prior",)),
            focus_scope=focus_scope,
            cause=str(data.get("cause") or "validated_policy_prior"),
            expected_effect=str(data.get("expected_effect") or
                                "Apply a validated behavior policy for this matched task stratum."),
        )
        return candidate

    def policy_mapping(self) -> dict[str, Any]:
        return {
            "candidate_id": self.candidate_id,
            "cognitive_mode": self.cognitive_mode,
            "framework_modes": dict(self.framework_modes),
            "controls": dict(self.controls),
            "focus_scope": self.focus_scope,
            "focus_criteria": (list(self.focus_criteria)
                               if self.focus_scope == "explicit" else "$current_attention"),
            "statework_preferences": list(self.statework_preferences),
            "reason_codes": list(self.reason_codes),
            "cause": self.cause,
            "expected_effect": self.expected_effect,
        }


@dataclass(frozen=True)
class BehaviorPolicyPrior:
    """A policy candidate backed by a promoted independent experiment receipt."""

    candidate: BehaviorCandidate
    profile_id: str
    profile_hash: str
    receipt_id: str
    experiment_id: str
    context: Mapping[str, Any]
    subject: Mapping[str, Any]
    condition: Mapping[str, Any]
    sharing_scope: str
    evidence: CandidateEvidence
    version: str = POLICY_PRIOR_VERSION
    _seal: object = field(default=None, repr=False, compare=False)

    @property
    def sample_count(self) -> int:
        return self.evidence.sample_count

    @property
    def holdout_count(self) -> int:
        return self.evidence.holdout_count

    def __post_init__(self) -> None:
        if self._seal is not _VALIDATED_PRIOR_SEAL:
            raise ValueError("behavior policy priors must come from a validated promoted profile")
        if self.version != POLICY_PRIOR_VERSION:
            raise ValueError("unsupported behavior policy prior version")
        for name, value in (("profile_id", self.profile_id), ("profile_hash", self.profile_hash),
                            ("receipt_id", self.receipt_id), ("experiment_id", self.experiment_id)):
            if not isinstance(value, str) or not value or len(value) > 256:
                raise ValueError(f"behavior policy prior {name} must be bounded text")
        if not isinstance(self.evidence, CandidateEvidence):
            raise ValueError("behavior policy prior requires validated candidate evidence")
        if self.evidence.evidence_class != "validated_experiment":
            raise ValueError("behavior policy prior requires validated experiment evidence")
        object.__setattr__(self, "context", MappingProxyType(dict(self.context)))
        object.__setattr__(self, "subject", MappingProxyType(dict(self.subject)))
        object.__setattr__(self, "condition", MappingProxyType(dict(self.condition)))
        if self.sharing_scope not in {"agent_private", "application_shared", "cross_application"}:
            raise ValueError("unsupported behavior policy sharing scope")

    @classmethod
    def from_promoted_profile(
            cls, profile: Mapping[str, Any], *,
            sharing_authority: Any = None) -> tuple["BehaviorPolicyPrior", ...]:
        """Extract priors only from deployable profiles with passing receipts."""
        try:
            validate_profile(profile, require_deployable=True,
                             sharing_authority=sharing_authority)
        except (RoutingProfileError, TypeError, ValueError):
            return ()
        status = str(profile.get("lifecycle_status") or profile.get("status") or "")
        if status not in {"validated", "active"}:
            return ()
        evidence = dict(profile.get("evidence") or {})
        receipt = dict(evidence.get("receipt") or {})
        if receipt.get("decision") != "pass":
            return ()
        treatment_count = len(receipt.get("treatment_trajectory_ids") or ())
        holdout_rows = receipt.get("holdout_outcomes") or ()
        holdout_count = len(holdout_rows)
        if (treatment_count < 1 or holdout_count < 1
                or float(receipt.get("confidence_interval", [0])[0]) < 0):
            return ()
        policy_evidence = receipt.get("candidate_policy_evidence")
        if not isinstance(policy_evidence, Mapping):
            return ()
        try:
            evidence = CandidateEvidence(
                correct_progress_estimate=float(policy_evidence["correct_progress_rate"]),
                regression_estimate=float(policy_evidence["regression_rate"]),
                repeated_failure_estimate=float(policy_evidence["repeated_failure_rate"]),
                sample_count=int(policy_evidence["sample_count"]),
                holdout_count=int(policy_evidence["holdout_count"]),
                evidence_class="validated_experiment",
                confidence_interval=tuple(policy_evidence["confidence_interval"]),
                regression_confidence_interval=tuple(
                    policy_evidence["regression_confidence_interval"]),
                repeated_failure_confidence_interval=tuple(
                    policy_evidence["repeated_failure_confidence_interval"]),
            )
        except (KeyError, TypeError, ValueError):
            return ()
        if (evidence.sample_count != treatment_count
                or evidence.holdout_count != holdout_count):
            return ()

        priors = []
        for adjustment in profile.get("routing_adjustments") or ():
            if not isinstance(adjustment, Mapping):
                continue
            policy = adjustment.get("behavior_policy")
            if not isinstance(policy, Mapping):
                continue
            receipt_adjustment = receipt.get("candidate_adjustment") or {}
            if (not isinstance(receipt_adjustment, Mapping)
                    or receipt_adjustment.get("behavior_policy") != dict(policy)):
                continue
            try:
                candidate = BehaviorCandidate.from_policy_mapping(
                    policy, attention_criteria=())
                prior = cls(
                    candidate=candidate,
                    profile_id=str(profile.get("profile_id") or ""),
                    profile_hash=str(profile.get("profile_hash") or ""),
                    receipt_id=str(receipt.get("receipt_id") or ""),
                    experiment_id=str(receipt.get("experiment_id") or ""),
                    context=dict(profile.get("context") or {}),
                    subject=dict(profile.get("subject") or {}),
                    condition=dict(adjustment.get("condition") or {}),
                    sharing_scope=str(profile.get("sharing_scope") or "agent_private"),
                    evidence=evidence,
                    _seal=_VALIDATED_PRIOR_SEAL,
                )
            except (KeyError, TypeError, ValueError):
                continue
            priors.append(prior)
        return tuple(priors[:_MAX_PRIORS])

    def matches(self, context: Mapping[str, Any]) -> bool:
        if not isinstance(context, Mapping):
            return False
        # Learned policy strata are exact. Missing host facts never act as a
        # wildcard, and compatibility constraints must all be present.
        for expected in (self.subject, self.context):
            for key, value in expected.items():
                if key == "compatibility_constraints":
                    if not isinstance(value, Mapping):
                        return False
                    if any(field not in context or context[field] != wanted
                           for field, wanted in value.items()):
                        return False
                elif key not in context or context[key] != value:
                    return False
        if self.sharing_scope != "agent_private":
            if self.profile_hash not in set(context.get("adopted_profile_hashes") or ()):
                return False
        if self.sharing_scope == "cross_application":
            allowed = set(context.get("authorized_target_application_ids") or ())
            if context.get("application_id") not in allowed:
                return False
            constraints = self.context.get("compatibility_constraints")
            if not isinstance(constraints, Mapping) or any(
                    context.get(field) != expected
                    for field, expected in constraints.items()):
                return False
        if not condition_matches(self.condition, context):
            return False
        return True

    def to_dict(self) -> dict[str, Any]:
        return {
            "version": self.version,
            "candidate": self.candidate.policy_mapping(),
            "profile_id": self.profile_id,
            "profile_hash": self.profile_hash,
            "receipt_id": self.receipt_id,
            "experiment_id": self.experiment_id,
            "context": dict(self.context),
            "subject": dict(self.subject),
            "condition": dict(self.condition),
            "sharing_scope": self.sharing_scope,
            "evidence": self.evidence.to_dict(),
        }


@dataclass(frozen=True)
class BehaviorPolicyConstraints:
    current_state: BehaviorState
    available_frameworks: tuple[str, ...]
    goal_set: GoalSetSnapshot | None
    required_mode: str | None = None


class BehaviorConstraintResolver:
    """Apply host, CFW, CSW, and goal-contract floors before scoring."""

    def reject_reason(self, candidate: BehaviorCandidate,
                      constraints: BehaviorPolicyConstraints,
                      csw_snapshot: CSWBehaviorSnapshot) -> str | None:
        current = constraints.current_state
        if candidate.framework_modes.get("ward") != "mandatory":
            return "ward_hard_floor"
        if (constraints.required_mode is not None
                and candidate.cognitive_mode != constraints.required_mode):
            return "host_or_goal_required_mode"
        if candidate.cognitive_mode == "READY_TO_COMPLETE":
            if constraints.goal_set is None or constraints.goal_set.required_counts[
                    "remaining_required"] != 0:
                return "required_goal_not_verified"
        if candidate.cognitive_mode == "BLOCKED" and constraints.goal_set is not None:
            if constraints.goal_set.runnable_items:
                return "runnable_required_goal_exists"
        if not set(candidate.focus_criteria).issubset(
                {item.criterion_id for item in constraints.goal_set.items}
                if constraints.goal_set is not None else set(candidate.focus_criteria)):
            return "focus_escapes_goal_contract"
        if constraints.goal_set is not None:
            runnable = {item.criterion_id for item in constraints.goal_set.runnable_items}
            if not set(candidate.focus_criteria).issubset(runnable):
                return "focus_includes_non_runnable_goal"
        for name, mode in candidate.framework_modes.items():
            if (mode != current.framework_modes.get(name)
                    and name not in set(constraints.available_frameworks)):
                return "framework_not_available"
        eligible = {item.statework_id for item in csw_snapshot.eligible_stateworks}
        active = set(csw_snapshot.active_stateworks)
        if any(item not in eligible or item in active
               for item in candidate.statework_preferences):
            return "statework_not_eligible"
        # Reuse the canonical BehaviorState validators for the configuration
        # surface while clearing task-local intervention bookkeeping.
        try:
            BehaviorState(
                cognitive_mode=candidate.cognitive_mode,
                framework_modes=candidate.framework_modes,
                focus_criteria=candidate.focus_criteria,
                **candidate.controls,
            )
        except (TypeError, ValueError):
            return "behavior_configuration_invalid"
        return None


@dataclass(frozen=True)
class SemanticCandidateEvidence:
    """Advisory semantic support for one already-legal candidate."""

    candidate_id: str
    goal_alignment_support: float | None = None
    retry_risk: float | None = None
    drift_risk: float | None = None

    def __post_init__(self) -> None:
        if not isinstance(self.candidate_id, str) or not self.candidate_id:
            raise ValueError("semantic candidate evidence requires a candidate ID")
        for name in ("goal_alignment_support", "retry_risk", "drift_risk"):
            value = getattr(self, name)
            if value is not None and (not isinstance(value, (int, float))
                                      or not 0.0 <= float(value) <= 1.0):
                raise ValueError(f"semantic {name} must be between zero and one")

    @property
    def support_score(self) -> float | None:
        values = []
        if self.goal_alignment_support is not None:
            values.append(float(self.goal_alignment_support))
        if self.retry_risk is not None:
            values.append(1.0 - float(self.retry_risk))
        if self.drift_risk is not None:
            values.append(1.0 - float(self.drift_risk))
        return sum(values) / len(values) if values else None


def _fairness_is_forced(legal: Sequence[tuple[BehaviorCandidate, "CandidateScore"]],
                        constraints: BehaviorPolicyConstraints) -> bool:
    """True when an external authority makes a fairness breach unavoidable.

    A host-required mode, a CFW requirement, or the WARD floor outrank the
    fairness preference: the system must still act legally rather than refuse to
    act. In that case fairness cannot be a hard constraint, so it degrades to the
    ranking tiebreak.
    """
    return constraints.required_mode is not None


def _would_violate_fairness(score: "CandidateScore") -> bool:
    """True when a candidate's projected lease breaches the fairness bound.

    ``starvation_risk`` is normalized projected age over the bound, so a value
    above one means the candidate would carry an unattended criterion past it.
    """
    return (score.starvation_risk is not None
            and score.starvation_risk > 1.0)


@dataclass(frozen=True)
class CandidateScore:
    candidate_id: str
    evidence: CandidateEvidence
    decision_support: float
    semantic_support: float | None
    starvation_risk: float | None
    estimated_cost: float

    @property
    def evidence_source(self) -> str:
        return self.evidence.evidence_class

    @property
    def evidence_class(self) -> str:
        return self.evidence.evidence_class

    @property
    def correct_progress_lower_bound(self) -> float | None:
        return (self.evidence.confidence_interval[0]
                if self.evidence.confidence_interval is not None else None)

    @property
    def regression_upper_bound(self) -> float | None:
        return (self.evidence.regression_confidence_interval[1]
                if self.evidence.regression_confidence_interval is not None else None)


@dataclass(frozen=True)
class PolicySelection:
    candidate: BehaviorCandidate | None
    score: CandidateScore | None
    disposition: str = "selected"
    rejected: Mapping[str, str] = field(default_factory=dict)
    ambiguity_margin: float = 1.0

    def __post_init__(self) -> None:
        if self.disposition not in {
                "selected", "abstain_insufficient_evidence", "abstain_ambiguous"}:
            raise ValueError("unsupported policy selection disposition")
        if (self.disposition == "selected") != (self.candidate is not None
                                                   and self.score is not None):
            raise ValueError("selected policy disposition must carry one candidate and score")
        if self.disposition != "selected" and (self.candidate is not None or self.score is not None):
            raise ValueError("abstained policy selection cannot fabricate a candidate or score")
        if not 0.0 <= float(self.ambiguity_margin) <= 1.0:
            raise ValueError("policy ambiguity margin must be between zero and one")

    @property
    def abstained(self) -> bool:
        return self.disposition != "selected"

    @property
    def abstention_reason(self) -> str | None:
        return None if self.disposition == "selected" else self.disposition


class BehaviorPolicySelector:
    """Select legal policies conservatively and abstain on weak learned evidence.

    Deterministic controller rules remain the fallback when there is no matched
    promoted evidence. A learned policy must clear a conservative confidence
    bound before it can displace the current policy.
    """

    def __init__(self, resolver: BehaviorConstraintResolver | None = None, *,
                 minimum_supported_progress_probability: float = 0.60,
                 maximum_supported_regression_probability: float = 0.20,
                 minimum_candidate_margin: float = 0.10) -> None:
        for name, value in (
                ("minimum supported progress probability",
                 minimum_supported_progress_probability),
                ("maximum supported regression probability",
                 maximum_supported_regression_probability),
                ("minimum candidate margin", minimum_candidate_margin)):
            if not isinstance(value, (int, float)) or not 0.0 <= float(value) <= 1.0:
                raise ValueError(f"{name} must be between zero and one")
        self.resolver = resolver or BehaviorConstraintResolver()
        self.minimum_supported_progress_probability = float(
            minimum_supported_progress_probability)
        self.maximum_supported_regression_probability = float(
            maximum_supported_regression_probability)
        self.minimum_candidate_margin = float(minimum_candidate_margin)

    def select(self, candidates: Iterable[BehaviorCandidate], *,
               constraints: BehaviorPolicyConstraints,
               csw_snapshot: CSWBehaviorSnapshot,
               goal_set: GoalSetSnapshot | None,
               policy_context: Mapping[str, Any],
               priors: Iterable[BehaviorPolicyPrior] = (),
               semantic_evidence: Mapping[str, SemanticCandidateEvidence] | None = None,
               rule_support: Mapping[str, float] | None = None,
               attention_lease: AttentionLease | None = None,
               attention_last_seen: Mapping[str, int] | None = None,
               current_action_index: int | None = None,
               ) -> PolicySelection:
        values = tuple(candidates)
        prior_values = tuple(priors)
        if not 1 <= len(values) <= _MAX_CANDIDATES:
            raise ValueError("policy selector requires one to eight bounded candidates")
        if len({item.candidate_id for item in values}) != len(values):
            raise ValueError("policy candidate IDs must be unique")
        if len(prior_values) > _MAX_PRIORS:
            raise ValueError("behavior policy prior count exceeds its bound")
        matching = [item for item in prior_values if item.matches(policy_context)]
        legal: list[tuple[BehaviorCandidate, CandidateScore]] = []
        rejected: dict[str, str] = {}
        semantic_by_id = dict(semantic_evidence or {})
        rule_support_by_id = dict(rule_support or {})
        attention_history = dict(attention_last_seen or {})
        if (attention_lease is None) != (current_action_index is None):
            raise ValueError("starvation scoring requires both a lease and action index")
        if current_action_index is not None and (
                type(current_action_index) is not int or current_action_index < 0):
            raise ValueError("starvation scoring action index is invalid")
        if goal_set is None and attention_lease is not None:
            raise ValueError("starvation scoring requires a host goal set")
        if (len(semantic_by_id) > _MAX_CANDIDATES
                or any(key != item.candidate_id
                       for key, item in semantic_by_id.items())
                or len(rule_support_by_id) > _MAX_CANDIDATES
                or any(not isinstance(value, (int, float))
                       or not 0.0 <= float(value) <= 1.0
                       for value in rule_support_by_id.values())):
            raise ValueError("semantic evidence must be keyed by bounded candidate IDs")
        for candidate in values:
            reason = self.resolver.reject_reason(candidate, constraints, csw_snapshot)
            if reason:
                rejected[candidate.candidate_id] = reason
                continue
            applicable = [item for item in matching
                          if item.candidate.candidate_id == candidate.candidate_id]
            # Overlapping profiles are not pooled. Choose the most specific
            # exact profile, then the larger independent sample, then stable ID.
            prior = max(applicable, key=lambda item: (
                len(item.subject) + len(item.context), item.sample_count,
                item.profile_id), default=None)
            semantic = semantic_by_id.get(candidate.candidate_id)
            evidence = (prior.evidence if prior is not None else
                        CandidateEvidence(
                            evidence_class=("deterministic_rule"
                                            if "deterministic_rule" in candidate.reason_codes
                                            else "semantic_support" if semantic is not None
                                            else "unknown")))
            progress_lower_bound = evidence.confidence_interval[0] \
                if evidence.confidence_interval is not None else None
            regression_upper_bound = evidence.regression_confidence_interval[1] \
                if evidence.regression_confidence_interval is not None else None
            learned_supported = bool(
                evidence.evidence_class == "validated_experiment"
                and progress_lower_bound is not None
                and regression_upper_bound is not None
                and progress_lower_bound >= self.minimum_supported_progress_probability
                and regression_upper_bound <= self.maximum_supported_regression_probability)
            semantic_support = semantic.support_score if semantic is not None else None
            if learned_supported:
                repeat_upper = (evidence.repeated_failure_confidence_interval[1]
                                if evidence.repeated_failure_confidence_interval else 0.5)
                empirical_quality = max(0.0, progress_lower_bound
                                        - 0.5 * regression_upper_bound
                                        - 0.25 * repeat_upper)
                decision_support = 0.60 + 0.40 * empirical_quality
            elif candidate.candidate_id in rule_support_by_id:
                decision_support = float(rule_support_by_id[candidate.candidate_id])
                if semantic_support is not None:
                    # Advisory Laya evidence can raise a candidate's support
                    # without weakening a stronger deterministic floor.
                    decision_support = max(
                        decision_support, 0.35 + 0.40 * semantic_support)
            elif "deterministic_rule" in candidate.reason_codes:
                decision_support = 0.82
            elif semantic_support is not None:
                # Semantic evidence is advisory and cannot become a hard gate.
                decision_support = 0.35 + 0.40 * semantic_support
            elif "continue_current" in candidate.reason_codes:
                decision_support = 0.40
            else:
                decision_support = 0.25
            estimated_cost = self._estimated_cost(candidate)
            starvation_risk = (
                projected_starvation_risk(
                    goal_set,
                    candidate_focus=candidate.focus_criteria,
                    last_seen=attention_history,
                    action_index=current_action_index,
                    lease_actions=attention_lease.max_actions,
                )
                if attention_lease is not None and current_action_index is not None
                else None)
            legal.append((candidate, CandidateScore(
                candidate_id=candidate.candidate_id,
                evidence=evidence,
                decision_support=decision_support,
                semantic_support=semantic_support,
                starvation_risk=starvation_risk,
                estimated_cost=estimated_cost,
            )))
        # Fairness is a hard constraint, not a preference. A candidate whose
        # projected lease would push an unattended runnable criterion past the
        # round-robin bound is excluded unless a host or CFW requirement forces
        # it, because the production invariant is zero fairness violations.
        fairness_forced = _fairness_is_forced(legal, constraints)
        if not fairness_forced:
            bounded = [pair for pair in legal
                       if not _would_violate_fairness(pair[1])]
            if bounded:
                legal = bounded
        if not legal:
            raise ValueError("all behavior candidates violate host, CFW, CSW, or goal constraints")

        # Starvation pressure is a tiebreak between otherwise legal candidates,
        # never an opaque weighted reward competing with evidence.
        ranked = sorted(legal, key=lambda pair: (
            pair[1].decision_support,
            pair[1].correct_progress_lower_bound
            if pair[1].correct_progress_lower_bound is not None else -1.0,
            -(pair[1].regression_upper_bound
              if pair[1].regression_upper_bound is not None else 1.0),
            -(pair[1].starvation_risk
              if pair[1].starvation_risk is not None else 0.0),
            -pair[1].estimated_cost,
            pair[0].candidate_id,
        ), reverse=True)
        best = ranked[0]
        runner_up = ranked[1] if len(ranked) > 1 else None
        margin = (best[1].decision_support - runner_up[1].decision_support
                  if runner_up is not None else 1.0)
        if constraints.required_mode is None and runner_up is not None:
            has_continuation = any(
                "continue_current" in item[0].reason_codes for item in ranked)
            has_information_fallback = any(
                "abstention_fallback" in item[0].reason_codes for item in ranked)
            has_decision_evidence = any(
                item[1].evidence.evidence_class in {
                    "deterministic_rule", "validated_experiment", "semantic_support"}
                or item[1].semantic_support is not None
                for item in ranked)
            if (has_continuation and has_information_fallback
                    and not has_decision_evidence):
                return PolicySelection(
                    None, None, "abstain_insufficient_evidence",
                    MappingProxyType(rejected), margin)
            matched_but_unsupported = any(
                item[1].evidence.evidence_class == "validated_experiment"
                and not (item[1].correct_progress_lower_bound is not None
                         and item[1].regression_upper_bound is not None
                         and item[1].correct_progress_lower_bound
                         >= self.minimum_supported_progress_probability
                         and item[1].regression_upper_bound
                         <= self.maximum_supported_regression_probability)
                for item in ranked)
            best_is_supported_experiment = (
                best[1].evidence.evidence_class == "validated_experiment"
                and best[1].correct_progress_lower_bound is not None
                and best[1].regression_upper_bound is not None
                and best[1].correct_progress_lower_bound
                >= self.minimum_supported_progress_probability
                and best[1].regression_upper_bound
                <= self.maximum_supported_regression_probability)
            if (matched_but_unsupported and not best_is_supported_experiment
                    and has_continuation):
                return PolicySelection(
                    None, None, "abstain_insufficient_evidence",
                    MappingProxyType(rejected), margin)
            if (margin < self.minimum_candidate_margin
                    and best[1].evidence.evidence_class not in {
                        "deterministic_rule", "validated_experiment"}):
                return PolicySelection(
                    None, None, "abstain_ambiguous", MappingProxyType(rejected), margin)
        return PolicySelection(best[0], best[1], "selected",
                               MappingProxyType(rejected), margin)

    @staticmethod
    def _estimated_cost(candidate: BehaviorCandidate) -> float:
        cost = 0.5
        cost += {"disabled": -0.12, "low": -0.08, "normal": 0.0,
                 "bounded": -0.04}[candidate.controls["exploration_budget"]]
        cost += {"compact": -0.08, "criterion_focused": -0.04,
                 "standard": 0.0}[candidate.controls["context_strategy"]]
        cost += {"passive": -0.03, "normal": 0.0, "high": 0.05,
                 "strict": 0.08}[candidate.controls["verification_intensity"]]
        return min(1.0, max(0.0, cost))


