"""Bounded, auditable selection among legal behavior configurations.

This selector is deliberately small. It considers only candidates generated by
the deterministic controller and scores them from explicit evidence fields.
Validated experiment receipts may change the ordering; raw behavioral history
cannot.
"""
from __future__ import annotations

from dataclasses import dataclass, field
import hashlib
import json
from math import sqrt
from types import MappingProxyType
from typing import Any, Iterable, Mapping

from ..behavior_state import (BEHAVIOR_MODES, FRAMEWORK_MODES, BehaviorState,
                              CSWBehaviorSnapshot, GoalSetSnapshot)
from ..routing_profiles import RoutingProfileError, condition_matches, validate_profile


POLICY_PRIOR_VERSION = "1.0.0"
_CONTROL_VALUES = {
    "verification_intensity": {"passive", "normal", "high", "strict"},
    "exploration_budget": {"disabled", "low", "normal", "bounded"},
    "retry_policy": {"normal", "materially_different_only", "no_retry"},
    "recovery_level": {0, 1, 2, 3},
    "context_strategy": {"standard", "compact", "criterion_focused"},
    "response_strategy": {"direct", "detailed", "structured"},
}
_CONTROL_NAMES = tuple(_CONTROL_VALUES)
_MAX_CANDIDATES = 8
_MAX_PRIORS = 64
_VALIDATED_PRIOR_SEAL = object()


def _canonical(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False, allow_nan=False)


def candidate_id_for(*, cognitive_mode: str, framework_modes: Mapping[str, str],
                     controls: Mapping[str, Any], focus_scope: str,
                     statework_preferences: Iterable[str],
                     focus_criteria: Iterable[str] = ()) -> str:
    """Return a stable identity for an exact or attention-bound policy."""
    if focus_scope not in {"current_attention", "explicit"}:
        raise ValueError("unsupported policy focus scope")
    identity = {
        "candidate_version": "1.0.0",
        "cognitive_mode": cognitive_mode,
        "framework_modes": dict(sorted((str(k).lower(), str(v))
                                        for k, v in framework_modes.items())),
        "controls": dict(sorted(controls.items())),
        "focus_scope": focus_scope,
        "focus_criteria": (list(focus_criteria) if focus_scope == "explicit" else []),
        "statework_preferences": list(statework_preferences),
    }
    return "behavior-" + hashlib.sha256(_canonical(identity).encode()).hexdigest()[:24]


@dataclass(frozen=True)
class BehaviorCandidate:
    """One bounded behavior configuration considered by the fast loop."""

    candidate_id: str
    cognitive_mode: str
    framework_modes: Mapping[str, str]
    controls: Mapping[str, Any]
    focus_criteria: tuple[str, ...]
    statework_preferences: tuple[str, ...]
    reason_codes: tuple[str, ...] = ()
    focus_scope: str = "current_attention"
    cause: str = "deterministic_policy"
    expected_effect: str = "Apply the selected bounded behavior policy."

    def __post_init__(self) -> None:
        if not isinstance(self.candidate_id, str) or not self.candidate_id or len(self.candidate_id) > 128:
            raise ValueError("behavior candidate ID must be bounded text")
        if self.cognitive_mode not in BEHAVIOR_MODES:
            raise ValueError("behavior candidate has an unsupported cognitive mode")
        frameworks = {str(key).lower(): str(value)
                      for key, value in self.framework_modes.items()}
        if (len(frameworks) > 16 or any(value not in FRAMEWORK_MODES
                                        for value in frameworks.values())):
            raise ValueError("behavior candidate framework modes are malformed")
        controls = dict(self.controls)
        if set(controls) != set(_CONTROL_NAMES):
            raise ValueError("behavior candidate must specify every bounded control")
        if any(value not in _CONTROL_VALUES[key] for key, value in controls.items()):
            raise ValueError("behavior candidate controls are malformed")
        focus = tuple(self.focus_criteria)
        preferences = tuple(self.statework_preferences)
        reasons = tuple(self.reason_codes)
        for name, values, maximum in (("focus criteria", focus, 8),
                                      ("StateWork preferences", preferences, 4),
                                      ("reason codes", reasons, 16)):
            if (len(values) > maximum or len(values) != len(set(values))
                    or any(not isinstance(value, str) or not value or len(value) > 128
                           for value in values)):
                raise ValueError(f"behavior candidate {name} exceed their bounds")
        if self.focus_scope not in {"current_attention", "explicit"}:
            raise ValueError("unsupported behavior candidate focus scope")
        if not isinstance(self.cause, str) or not self.cause or len(self.cause) > 128:
            raise ValueError("behavior candidate cause must be bounded text")
        if (not isinstance(self.expected_effect, str) or not self.expected_effect.strip()
                or len(self.expected_effect) > 512):
            raise ValueError("behavior candidate expected effect must be bounded text")
        expected_id = candidate_id_for(
            cognitive_mode=self.cognitive_mode, framework_modes=frameworks,
            controls=controls, focus_scope=self.focus_scope,
            statework_preferences=preferences, focus_criteria=focus)
        if self.candidate_id != expected_id:
            raise ValueError("behavior candidate ID does not match its configuration")
        object.__setattr__(self, "framework_modes", MappingProxyType(frameworks))
        object.__setattr__(self, "controls", MappingProxyType(controls))
        object.__setattr__(self, "focus_criteria", focus)
        object.__setattr__(self, "statework_preferences", preferences)
        object.__setattr__(self, "reason_codes", reasons)

    @classmethod
    def from_state(cls, state: BehaviorState, *, focus_criteria: Iterable[str],
                   statework_preferences: Iterable[str], reason_codes: Iterable[str],
                   cause: str, expected_effect: str,
                   focus_scope: str = "current_attention") -> "BehaviorCandidate":
        controls = {name: getattr(state, name) for name in _CONTROL_NAMES}
        frameworks = dict(state.framework_modes)
        frameworks["ward"] = "mandatory"
        focus = tuple(focus_criteria)
        preferences = tuple(statework_preferences)
        return cls(
            candidate_id=candidate_id_for(
                cognitive_mode=state.cognitive_mode, framework_modes=frameworks,
                controls=controls, focus_scope=focus_scope,
                statework_preferences=preferences,
                focus_criteria=focus),
            cognitive_mode=state.cognitive_mode,
            framework_modes=frameworks, controls=controls,
            focus_criteria=focus,
            statework_preferences=preferences,
            reason_codes=tuple(reason_codes), focus_scope=focus_scope,
            cause=cause, expected_effect=expected_effect)

    @classmethod
    def from_policy_mapping(cls, value: Mapping[str, Any], *,
                            attention_criteria: Iterable[str]) -> "BehaviorCandidate":
        data = dict(value)
        allowed = {"candidate_id", "cognitive_mode", "framework_modes", "controls",
                   "focus_scope", "focus_criteria", "statework_preferences",
                   "reason_codes", "cause", "expected_effect"}
        if set(data) - allowed:
            raise ValueError("behavior policy candidate contains unknown fields")
        focus_scope = str(data.get("focus_scope") or "current_attention")
        if focus_scope != "current_attention":
            raise ValueError("promoted policies must bind focus to current host attention")
        if data.get("focus_criteria", "$current_attention") != "$current_attention":
            raise ValueError("promoted policies cannot override the host attention lease")
        focus = tuple(attention_criteria)
        candidate = cls(
            candidate_id=str(data.get("candidate_id") or ""),
            cognitive_mode=str(data["cognitive_mode"]),
            framework_modes=dict(data.get("framework_modes") or {}),
            controls=dict(data["controls"]),
            focus_criteria=focus,
            statework_preferences=tuple(data.get("statework_preferences") or ()),
            reason_codes=tuple(data.get("reason_codes") or ("validated_policy_prior",)),
            focus_scope=focus_scope,
            cause=str(data.get("cause") or "validated_policy_prior"),
            expected_effect=str(data.get("expected_effect") or
                                "Apply a validated behavior policy for this matched task stratum."),
        )
        return candidate

    def policy_mapping(self) -> dict[str, Any]:
        return {
            "candidate_id": self.candidate_id,
            "cognitive_mode": self.cognitive_mode,
            "framework_modes": dict(self.framework_modes),
            "controls": dict(self.controls),
            "focus_scope": self.focus_scope,
            "focus_criteria": (list(self.focus_criteria)
                               if self.focus_scope == "explicit" else "$current_attention"),
            "statework_preferences": list(self.statework_preferences),
            "reason_codes": list(self.reason_codes),
            "cause": self.cause,
            "expected_effect": self.expected_effect,
        }


@dataclass(frozen=True)
class BehaviorPolicyPrior:
    """A policy candidate backed by a promoted independent experiment receipt."""

    candidate: BehaviorCandidate
    profile_id: str
    profile_hash: str
    receipt_id: str
    experiment_id: str
    context: Mapping[str, Any]
    subject: Mapping[str, Any]
    condition: Mapping[str, Any]
    sharing_scope: str
    correct_progress_probability: float
    regression_probability: float
    repeated_failure_probability: float | None
    sample_count: int
    holdout_count: int
    version: str = POLICY_PRIOR_VERSION
    _seal: object = field(default=None, repr=False, compare=False)

    def __post_init__(self) -> None:
        if self._seal is not _VALIDATED_PRIOR_SEAL:
            raise ValueError("behavior policy priors must come from a validated promoted profile")
        if self.version != POLICY_PRIOR_VERSION:
            raise ValueError("unsupported behavior policy prior version")
        for name, value in (("profile_id", self.profile_id), ("profile_hash", self.profile_hash),
                            ("receipt_id", self.receipt_id), ("experiment_id", self.experiment_id)):
            if not isinstance(value, str) or not value or len(value) > 256:
                raise ValueError(f"behavior policy prior {name} must be bounded text")
        for name, value in (("correct-progress probability", self.correct_progress_probability),
                            ("regression probability", self.regression_probability)):
            if not 0.0 <= float(value) <= 1.0:
                raise ValueError(f"behavior policy prior {name} is outside [0, 1]")
        if (self.repeated_failure_probability is not None
                and not 0.0 <= float(self.repeated_failure_probability) <= 1.0):
            raise ValueError("repeated failure probability is outside [0, 1]")
        if type(self.sample_count) is not int or self.sample_count < 1:
            raise ValueError("behavior policy prior requires treatment samples")
        if type(self.holdout_count) is not int or self.holdout_count < 1:
            raise ValueError("behavior policy prior requires holdout samples")
        object.__setattr__(self, "context", MappingProxyType(dict(self.context)))
        object.__setattr__(self, "subject", MappingProxyType(dict(self.subject)))
        object.__setattr__(self, "condition", MappingProxyType(dict(self.condition)))
        if self.sharing_scope not in {"agent_private", "application_shared", "cross_application"}:
            raise ValueError("unsupported behavior policy sharing scope")

    @classmethod
    def from_promoted_profile(
            cls, profile: Mapping[str, Any], *,
            sharing_authority: Any = None) -> tuple["BehaviorPolicyPrior", ...]:
        """Extract priors only from deployable profiles with passing receipts."""
        try:
            validate_profile(profile, require_deployable=True,
                             sharing_authority=sharing_authority)
        except (RoutingProfileError, TypeError, ValueError):
            return ()
        status = str(profile.get("lifecycle_status") or profile.get("status") or "")
        if status not in {"validated", "active"}:
            return ()
        evidence = dict(profile.get("evidence") or {})
        receipt = dict(evidence.get("receipt") or {})
        if receipt.get("decision") != "pass":
            return ()
        treatment_count = len(receipt.get("treatment_trajectory_ids") or ())
        holdout_rows = receipt.get("holdout_outcomes") or ()
        holdout_count = len(holdout_rows)
        if (treatment_count < 1 or holdout_count < 1
                or float(receipt.get("confidence_interval", [0])[0]) < 0):
            return ()
        regressions = sum(
            isinstance(row, (tuple, list)) and len(row) == 2
            and str(row[1]).upper() == "FAIL" for row in holdout_rows)
        treatment_bad_rate = receipt.get("treatment_bad_rate")
        if not isinstance(treatment_bad_rate, (int, float)) or not 0 <= treatment_bad_rate <= 1:
            return ()
        progress_rate = 1.0 - float(treatment_bad_rate)
        # Jeffreys smoothing keeps small validated cohorts from becoming
        # absolute certainty while retaining the receipt's measured rate.
        progress_probability = (progress_rate * treatment_count + 0.5) / (treatment_count + 1.0)
        repeat_probability = receipt.get("repeated_failure_probability")
        if repeat_probability is not None and not 0.0 <= float(repeat_probability) <= 1.0:
            return ()

        priors = []
        for adjustment in profile.get("routing_adjustments") or ():
            if not isinstance(adjustment, Mapping):
                continue
            policy = adjustment.get("behavior_policy")
            if not isinstance(policy, Mapping):
                continue
            receipt_adjustment = receipt.get("candidate_adjustment") or {}
            if (not isinstance(receipt_adjustment, Mapping)
                    or receipt_adjustment.get("behavior_policy") != dict(policy)):
                continue
            try:
                candidate = BehaviorCandidate.from_policy_mapping(
                    policy, attention_criteria=())
                prior = cls(
                    candidate=candidate,
                    profile_id=str(profile.get("profile_id") or ""),
                    profile_hash=str(profile.get("profile_hash") or ""),
                    receipt_id=str(receipt.get("receipt_id") or ""),
                    experiment_id=str(receipt.get("experiment_id") or ""),
                    context=dict(profile.get("context") or {}),
                    subject=dict(profile.get("subject") or {}),
                    condition=dict(adjustment.get("condition") or {}),
                    sharing_scope=str(profile.get("sharing_scope") or "agent_private"),
                    correct_progress_probability=progress_probability,
                    regression_probability=regressions / holdout_count,
                    repeated_failure_probability=(
                        float(repeat_probability) if repeat_probability is not None else None),
                    sample_count=treatment_count, holdout_count=holdout_count,
                    _seal=_VALIDATED_PRIOR_SEAL,
                )
            except (KeyError, TypeError, ValueError):
                continue
            priors.append(prior)
        return tuple(priors[:_MAX_PRIORS])

    def matches(self, context: Mapping[str, Any]) -> bool:
        if not isinstance(context, Mapping):
            return False
        # Learned policy strata are exact. Missing host facts never act as a
        # wildcard, and compatibility constraints must all be present.
        for expected in (self.subject, self.context):
            for key, value in expected.items():
                if key == "compatibility_constraints":
                    if not isinstance(value, Mapping):
                        return False
                    if any(field not in context or context[field] != wanted
                           for field, wanted in value.items()):
                        return False
                elif key not in context or context[key] != value:
                    return False
        if self.sharing_scope != "agent_private":
            if self.profile_hash not in set(context.get("adopted_profile_hashes") or ()):
                return False
        if self.sharing_scope == "cross_application":
            allowed = set(context.get("authorized_target_application_ids") or ())
            if context.get("application_id") not in allowed:
                return False
            constraints = self.context.get("compatibility_constraints")
            if not isinstance(constraints, Mapping) or any(
                    context.get(field) != expected
                    for field, expected in constraints.items()):
                return False
        if not condition_matches(self.condition, context):
            return False
        return True

    def to_dict(self) -> dict[str, Any]:
        return {
            "version": self.version,
            "candidate": self.candidate.policy_mapping(),
            "profile_id": self.profile_id,
            "profile_hash": self.profile_hash,
            "receipt_id": self.receipt_id,
            "experiment_id": self.experiment_id,
            "context": dict(self.context),
            "subject": dict(self.subject),
            "condition": dict(self.condition),
            "sharing_scope": self.sharing_scope,
            "correct_progress_probability": self.correct_progress_probability,
            "regression_probability": self.regression_probability,
            "repeated_failure_probability": self.repeated_failure_probability,
            "sample_count": self.sample_count,
            "holdout_count": self.holdout_count,
        }


@dataclass(frozen=True)
class BehaviorPolicyConstraints:
    current_state: BehaviorState
    available_frameworks: tuple[str, ...]
    goal_set: GoalSetSnapshot | None
    required_mode: str | None = None


class BehaviorConstraintResolver:
    """Apply host, CFW, CSW, and goal-contract floors before scoring."""

    def reject_reason(self, candidate: BehaviorCandidate,
                      constraints: BehaviorPolicyConstraints,
                      csw_snapshot: CSWBehaviorSnapshot) -> str | None:
        current = constraints.current_state
        if candidate.framework_modes.get("ward") != "mandatory":
            return "ward_hard_floor"
        if (constraints.required_mode is not None
                and candidate.cognitive_mode != constraints.required_mode):
            return "host_or_goal_required_mode"
        if candidate.cognitive_mode == "READY_TO_COMPLETE":
            if constraints.goal_set is None or constraints.goal_set.required_counts[
                    "remaining_required"] != 0:
                return "required_goal_not_verified"
        if candidate.cognitive_mode == "BLOCKED" and constraints.goal_set is not None:
            if constraints.goal_set.runnable_items:
                return "runnable_required_goal_exists"
        if not set(candidate.focus_criteria).issubset(
                {item.criterion_id for item in constraints.goal_set.items}
                if constraints.goal_set is not None else set(candidate.focus_criteria)):
            return "focus_escapes_goal_contract"
        if constraints.goal_set is not None:
            runnable = {item.criterion_id for item in constraints.goal_set.runnable_items}
            if not set(candidate.focus_criteria).issubset(runnable):
                return "focus_includes_non_runnable_goal"
        for name, mode in candidate.framework_modes.items():
            if (mode != current.framework_modes.get(name)
                    and name not in set(constraints.available_frameworks)):
                return "framework_not_available"
        eligible = {item.statework_id for item in csw_snapshot.eligible_stateworks}
        active = set(csw_snapshot.active_stateworks)
        if any(item not in eligible or item in active
               for item in candidate.statework_preferences):
            return "statework_not_eligible"
        # Reuse the canonical BehaviorState validators for the configuration
        # surface while clearing task-local intervention bookkeeping.
        try:
            BehaviorState(
                cognitive_mode=candidate.cognitive_mode,
                framework_modes=candidate.framework_modes,
                focus_criteria=candidate.focus_criteria,
                **candidate.controls,
            )
        except (TypeError, ValueError):
            return "behavior_configuration_invalid"
        return None


@dataclass(frozen=True)
class CandidateScore:
    candidate_id: str
    correct_progress_probability: float
    regression_probability: float
    repeated_failure_probability: float
    starvation_probability: float
    estimated_cost: float
    evidence_source: str


@dataclass(frozen=True)
class PolicySelection:
    candidate: BehaviorCandidate
    score: CandidateScore
    rejected: Mapping[str, str] = field(default_factory=dict)


class BehaviorPolicySelector:
    """Lexicographic policy selection with deterministic fallback tie breaks."""

    def __init__(self, resolver: BehaviorConstraintResolver | None = None) -> None:
        self.resolver = resolver or BehaviorConstraintResolver()

    def select(self, candidates: Iterable[BehaviorCandidate], *,
               constraints: BehaviorPolicyConstraints,
               csw_snapshot: CSWBehaviorSnapshot,
               goal_set: GoalSetSnapshot | None,
               policy_context: Mapping[str, Any],
               priors: Iterable[BehaviorPolicyPrior] = ()) -> PolicySelection:
        values = tuple(candidates)
        prior_values = tuple(priors)
        if not 1 <= len(values) <= _MAX_CANDIDATES:
            raise ValueError("policy selector requires one to eight bounded candidates")
        if len({item.candidate_id for item in values}) != len(values):
            raise ValueError("policy candidate IDs must be unique")
        if len(prior_values) > _MAX_PRIORS:
            raise ValueError("behavior policy prior count exceeds its bound")
        matching = [item for item in prior_values if item.matches(policy_context)]
        legal: list[tuple[BehaviorCandidate, CandidateScore]] = []
        rejected: dict[str, str] = {}
        runnable = tuple(goal_set.runnable_items) if goal_set is not None else ()
        for candidate in values:
            reason = self.resolver.reject_reason(candidate, constraints, csw_snapshot)
            if reason:
                rejected[candidate.candidate_id] = reason
                continue
            applicable = [item for item in matching
                          if item.candidate.candidate_id == candidate.candidate_id]
            # Overlapping profiles are not pooled. Choose the most specific
            # exact profile, then the larger independent sample, then stable ID.
            prior = max(applicable, key=lambda item: (
                len(item.subject) + len(item.context), item.sample_count,
                item.profile_id), default=None)
            correct_probability = (prior.correct_progress_probability if prior else 0.5)
            regression_probability = (prior.regression_probability if prior else 0.5)
            repeated_probability = (
                prior.repeated_failure_probability
                if prior and prior.repeated_failure_probability is not None
                else 0.5)
            focus = set(candidate.focus_criteria)
            starvation_probability = (
                sum(1 for item in runnable if item.criterion_id not in focus) / len(runnable)
                if runnable else 0.0)
            estimated_cost = self._estimated_cost(candidate)
            source = (f"validated_receipt:{prior.receipt_id}" if prior
                      else "deterministic_controller_fallback")
            legal.append((candidate, CandidateScore(
                candidate_id=candidate.candidate_id,
                correct_progress_probability=correct_probability,
                regression_probability=regression_probability,
                repeated_failure_probability=repeated_probability,
                starvation_probability=starvation_probability,
                estimated_cost=estimated_cost,
                evidence_source=source)))
        if not legal:
            raise ValueError("all behavior candidates violate host, CFW, CSW, or goal constraints")

        def rule_rank(candidate: BehaviorCandidate) -> int:
            return 1 if "deterministic_rule" in candidate.reason_codes else 0

        selected, score = max(legal, key=lambda pair: (
            pair[1].correct_progress_probability,
            -pair[1].regression_probability,
            -pair[1].repeated_failure_probability,
            -pair[1].starvation_probability,
            -pair[1].estimated_cost,
            rule_rank(pair[0]),
            pair[0].candidate_id,
        ))
        return PolicySelection(selected, score, MappingProxyType(rejected))

    @staticmethod
    def _estimated_cost(candidate: BehaviorCandidate) -> float:
        cost = 0.5
        cost += {"disabled": -0.12, "low": -0.08, "normal": 0.0,
                 "bounded": -0.04}[candidate.controls["exploration_budget"]]
        cost += {"compact": -0.08, "criterion_focused": -0.04,
                 "standard": 0.0}[candidate.controls["context_strategy"]]
        cost += {"passive": -0.03, "normal": 0.0, "high": 0.05,
                 "strict": 0.08}[candidate.controls["verification_intensity"]]
        return min(1.0, max(0.0, cost))


